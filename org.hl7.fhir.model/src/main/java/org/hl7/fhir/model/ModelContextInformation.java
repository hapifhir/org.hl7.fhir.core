package org.hl7.fhir.model;

import lombok.Getter;
import org.hl7.fhir.exceptions.FHIRException;
import org.hl7.fhir.model.core.CoreRegistration;
import org.hl7.fhir.model.core.formats.ParserBase;

import javax.annotation.Nonnull;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicInteger;

public class ModelContextInformation {

  //region compatibility shapes

  /**
   * The set of distinct registration shapes seen in this process, mapped to a small int id.
   * Two contexts are compatible exactly when they have the same shape, so compatibility is an
   * int comparison once each side has been canonicalised
   * <p>
   * This table holds only strings and boxed ints - it never references a ModelContextInformation,
   * a handler, or a parser factory, so caching in it does not keep any context alive. It is
   * bounded by the number of distinct registration shapes (in practice one or two per process),
   * not by the number of contexts created
   */
  private static final Map<String, Integer> SHAPES = new ConcurrentHashMap<>();
  private static final AtomicInteger SHAPE_IDS = new AtomicInteger();

  /**
   * If an application somehow generates unbounded distinct shapes (e.g. package ids that carry a
   * timestamp), stop interning and fall back to comparing the canonical forms directly, rather
   * than growing the table forever
   */
  private static final int MAX_SHAPES = 1000;

  private static final int STALE = -1;
  private static final int UNINTERNED = -2;

  //endregion

  private static final AtomicInteger MASTER_ID = new AtomicInteger();

  /** identifies this context in diagnostics - contexts are otherwise hard to tell apart */
  @Getter
  private final int id;

  public ModelContextInformation() {
    id = MASTER_ID.incrementAndGet();
    corePackage = CoreRegistration.register(this);
    packageList.add(corePackage);
  }

  /**
   * Copy an existing set of registrations into a new context information. This is what a worker
   * context that is copied from another one uses: the copy has to know about the same resources
   * as the original, or objects created under the original (which a copied worker context shares
   * by reference) are not usable under the copy
   * <p>
   * The registrations themselves are immutable and are shared rather than cloned. The lists are
   * not shared, so registering something on the copy does not change the original - the two just
   * stop being compatible from that point on, which is the correct answer
   * <p>
   * Note that CoreRegistration is deliberately not run here - the core registrations are already
   * in the source's resourceList, and running it again would register them twice
   */
  public ModelContextInformation(@Nonnull ModelContextInformation source) {
    id = MASTER_ID.incrementAndGet();
    corePackage = source.corePackage;
    packageList.addAll(source.packageList);
    resourceList.addAll(source.resourceList);
  }

  @Getter
  private String corePackage;

  /**
   * A list of packages on which the classes available to the context were generated from
   * The core context is in this list as well as in corePackage
   *
   */
  @Getter
  private Set<String> packageList = new HashSet<String>();

  /**
   * A list of all resources, and how they are supported
   */
  @Getter
  private List<ModelResourceInformation> resourceList = new ArrayList<>();

  /** name -> registration, rebuilt lazily after any registration. null = stale */
  private volatile Map<String, ModelResourceInformation> index;

  /** the interned shape id for the current registration set. STALE = not yet computed */
  private volatile int shapeId = STALE;

  /** the canonical form, kept only when the shape table is full (see MAX_SHAPES) */
  private volatile String canonicalForm;

  /**
   * This is only called from the generated CoreRegistration class
   *
   * @param name        - name of the resource
   * @param packageName - the package it was compiled from
   */
  public void registerCoreResource(@Nonnull String name, @Nonnull String packageName) {
    resourceList.add(new ModelResourceInformation(name, packageName, false, null));
    changed();
  }

  /**
   * Called to register support for a resource not defined in the base specification
   * This should only be called from code generated by the validator using -codegen
   *
   * note that the source package does not need to be published - it can be a private package
   *
   * @param name - name of the resource
   * @param packageName - the package it was compiled from
   * @param handler - the CustomResourceHandler that handles the implementation details
   */
  public void registerResource(@Nonnull String name, @Nonnull String packageName, boolean overrides, @Nonnull ParserBase.CustomResourceHandler handler) {
    ModelResourceInformation existing = getResourceInformation(name);
    if (existing != null && (existing.getHandler() != null || !overrides)) {
      throw new FHIRException("Resource with name " + name + " already registered");
    }
    resourceList.add(new ModelResourceInformation(name, packageName, overrides, handler));
    packageList.add(packageName);
    changed();
  }

  /**
   * Find the handler for a custom resource by name. Returns null if the name is not
   * registered, or is a core resource (core resources have no handler)
   * <p>
   * this is on the parsing hot path - once per resource parsed - so it goes through the index
   * rather than scanning the ~160 core registrations
   */
  public ParserBase.CustomResourceHandler getHandler(@Nonnull String name) {
    ModelResourceInformation mri = getResourceInformation(name);
    return mri == null ? null : mri.getHandler();
  }

  /**
   * true if the two model contexts have the same set up, and so objects created under one of
   * them can be used under the other
   * <p>
   * After the first call on each side this is an int comparison; the canonical form is only
   * rebuilt when something has been registered since the last call
   *
   * @param otherContext
   * @return
   */
  public boolean isCompatible(ModelContextInformation otherContext) {
    if (this == otherContext) {
      return true;
    }
    if (otherContext == null) {
      return false;
    }
    int s = shapeId();
    int o = otherContext.shapeId();
    if (s == UNINTERNED || o == UNINTERNED) {
      return canonicalForm().equals(otherContext.canonicalForm());
    }
    return s == o;
  }

  /**
   * get information about how a resource is implemented
   *
   * @param name
   * @return
   */
  private ModelResourceInformation getResourceInformation(String name) {
    Map<String, ModelResourceInformation> i = index;
    if (i == null) {
      i = new HashMap<>();
      for (ModelResourceInformation mri : resourceList) {
        // a later registration overrides an earlier one - registerResource only allows that
        // when overrides is true, and that's the one that should be found
        i.put(mri.getName(), mri);
      }
      index = i;
    }
    return i.get(name);
  }

  /** called whenever the registration set changes, to drop the derived state */
  private void changed() {
    index = null;
    shapeId = STALE;
    canonicalForm = null;
  }

  private int shapeId() {
    int s = shapeId;
    if (s == STALE) {
      String cf = canonicalForm();
      Integer known = SHAPES.get(cf);
      if (known != null) {
        s = known;
      } else if (SHAPES.size() >= MAX_SHAPES) {
        s = UNINTERNED;
      } else {
        s = SHAPES.computeIfAbsent(cf, k -> SHAPE_IDS.incrementAndGet());
      }
      // benign race: two threads canonicalising at once compute the same id
      shapeId = s;
    }
    return s;
  }

  /**
   * A stable string that captures the whole registration set, independent of the order things
   * were registered in
   */
  private String canonicalForm() {
    String cf = canonicalForm;
    if (cf == null) {
      List<String> keys = new ArrayList<>(resourceList.size());
      for (ModelResourceInformation mri : resourceList) {
        keys.add(mri.canonicalKey());
      }
      Collections.sort(keys);
      cf = String.join("\n", keys);
      canonicalForm = cf;
    }
    return cf;
  }

  public String toString() {
    return "ModelContext#" + id + " (" + corePackage + ", " + resourceList.size() + " resources)";
  }
}
