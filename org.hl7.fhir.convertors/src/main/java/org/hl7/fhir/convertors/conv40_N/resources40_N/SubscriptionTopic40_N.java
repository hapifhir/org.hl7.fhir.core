/**
 * SubscriptionTopic is new in R5, so it's a Basic in R4. identifier is Basic's; everything else is a cross-version
 * extension. R6 replaced resourceTrigger, eventTrigger, canFilterBy and notificationShape with trigger, which is a
 * 6.0 extension; the rest are 5.0
 */
public class SubscriptionTopic40_N {

  private static final String[] V5 = {"url", "version", "versionAlgorithm", "name", "title", "derivedFrom", "status", "experimental", "date",
    "publisher", "contact", "description", "useContext", "jurisdiction", "purpose", "copyright", "copyrightLabel", "approvalDate",
    "lastReviewDate", "effectivePeriod"};
  private static final String[] V6 = {"trigger"};

  public static org.hl7.fhir.model.core.SubscriptionTopic convertSubscriptionTopic(org.hl7.fhir.r4.model.Basic src) throws FHIRException {
    if (src == null)
      return null;
    if (!src.getCode().hasCoding("http://hl7.org/fhir/fhir-types", "SubscriptionTopic")) {
      throw new FHIRException("Error in logic: this basic resource is not an SubscriptionTopic");
    }
    org.hl7.fhir.model.core.SubscriptionTopic tgt = new org.hl7.fhir.model.core.SubscriptionTopic();
    ConversionContext40_N.INSTANCE.getVersionConvertor_40_N().copyDomainResource(src, tgt,
      CrossVersionElements40_N.urls("SubscriptionTopic", "5.0", V5, CrossVersionElements40_N.urls("SubscriptionTopic", "6.0", V6)));
    for (org.hl7.fhir.r4.model.Identifier t : src.getIdentifier())
      tgt.addIdentifier(Identifier40_N.convertIdentifier(t));
    CrossVersionElements40_N.extensionsToElements(src.getExtension(), tgt, "5.0", V5);
    CrossVersionElements40_N.extensionsToElements(src.getExtension(), tgt, "6.0", V6);
    return tgt;
  }

  public static org.hl7.fhir.r4.model.Basic convertSubscriptionTopic(org.hl7.fhir.model.core.SubscriptionTopic src) throws FHIRException {
    if (src == null)
      return null;
    org.hl7.fhir.r4.model.Basic tgt = new org.hl7.fhir.r4.model.Basic();
    ConversionContext40_N.INSTANCE.getVersionConvertor_40_N().copyDomainResource(src, tgt);
    tgt.getCode().getCodingFirstRep().setSystem("http://hl7.org/fhir/fhir-types").setCode("SubscriptionTopic"); // note use of R5 type system
    for (org.hl7.fhir.model.core.Identifier t : src.getIdentifierList())
      tgt.addIdentifier(Identifier40_N.convertIdentifier(t));
    CrossVersionElements40_N.elementsToExtensions(src, tgt.getExtension(), "5.0", V5);
    CrossVersionElements40_N.elementsToExtensions(src, tgt.getExtension(), "6.0", V6);
    return tgt;
  }
}
